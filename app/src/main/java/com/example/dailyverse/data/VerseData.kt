    private val shownIdx = mutableMapOf<String, MutableList<Int>>()

    fun getRandom(categoryId: String): Verse {
        val pool = verses[categoryId] ?: return Verse("말씀을 찾을 수 없습니다.", "", "")
        val shown = shownIdx.getOrPut(categoryId) { mutableListOf() }
        if (shown.size >= pool.size) shown.clear()
        val remaining = pool.indices.filter { it !in shown }
        val pick = remaining.random()
        shown.add(pick)
        return pool[pick]
    }
